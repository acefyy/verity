import { db, Report, Database } from '../db/database.js';

export function generateCaseAuditMarkdown(reportId: string, databaseInstance: Database = db): string {
  const report = databaseInstance.getReportById(reportId);
  if (!report) {
    throw new Error(`Report ${reportId} not found in database.`);
  }

  const resolution = databaseInstance.getModerationResolution(reportId);
  const evidenceList = databaseInstance.getEvidenceByReportId(reportId);
  const milestones = databaseInstance.getInvestigationMilestones(reportId);

  const submittedDate = new Date(report.createdAt).toISOString();
  const resolvedDate = resolution ? new Date(resolution.executedAt).toISOString() : 'Pending';

  const lines: string[] = [];

  lines.push(`# Verity Case Audit Report: ${report.reportCode}`);
  lines.push('');
  lines.push('## Executive Summary');
  lines.push(`- **Report ID:** \`${report.reportCode}\``);
  lines.push(`- **Internal UUID:** \`${report.id}\``);
  lines.push(`- **Status:** \`${report.status.toUpperCase()}\``);
  lines.push(`- **Target Member:** <@${report.reportedUserId}> (\`${report.reportedUserId}\`)`);
  lines.push(`- **Reporting Member:** <@${report.reporterId}> (\`${report.reporterId}\`)`);
  lines.push(`- **Server (Guild) ID:** \`${report.guildId}\``);
  lines.push(`- **Channel ID:** <#${report.channelId}> (\`${report.channelId}\`)`);
  lines.push(`- **Origin Message Link:** ${report.messageLink}`);
  lines.push(`- **Submitted At:** ${submittedDate}`);
  lines.push(`- **Switch Case Room:** \`${report.switchRoomId || 'None'}\``);
  lines.push('');

  lines.push('## Alleged Violation & Intake Claim');
  lines.push(`> ${report.reason.replace(/\n/g, '\n> ')}`);
  lines.push('');

  lines.push('## Forensic Evidence Audit');
  if (evidenceList.length === 0) {
    lines.push('*No evidence files attached during intake.*');
  } else {
    lines.push(`Total Attached Files: ${evidenceList.length}`);
    lines.push('');
    for (let i = 0; i < evidenceList.length; i++) {
      const ev = evidenceList[i];
      lines.push(`### Evidence Item #${i + 1}: \`${ev.filename}\``);
      lines.push(`- **MIME Type:** \`${ev.detectedMimeType}\``);
      lines.push(`- **Size:** ${ev.sizeBytes} bytes`);
      lines.push(`- **SHA-256 Hash:** \`${ev.sha256Hash}\``);
      lines.push(`- **URL:** ${ev.discordCdnUrl}`);
      lines.push('');
    }
  }
  lines.push('');

  lines.push('## Multi-Agent Investigation Log');
  if (milestones.length === 0) {
    lines.push('*No multi-agent milestones recorded.*');
  } else {
    for (const m of milestones) {
      const milestoneTime = new Date(m.completedAt).toISOString();
      lines.push(`### ${m.phase} (\`@${m.agentName}\`)`);
      lines.push(`*Recorded at: ${milestoneTime}*`);
      lines.push('');
      lines.push(m.content);
      lines.push('');
    }
  }

  lines.push('## Moderation Resolution');
  if (!resolution) {
    lines.push('*Case remains open or awaiting moderator decision.*');
  } else {
    lines.push(`- **Action Enforced:** \`${resolution.actionTaken.toUpperCase()}\``);
    lines.push(`- **Authorized By Moderator:** <@${resolution.moderatorId}> (\`${resolution.moderatorId}\`)`);
    lines.push(`- **Executed At:** ${resolvedDate}`);
    lines.push(`- **Target Member:** <@${resolution.targetUserId}> (\`${resolution.targetUserId}\`)`);
    lines.push('');
    lines.push(`> **Official Reason:**`);
    lines.push(`> ${resolution.officialReason.replace(/\n/g, '\n> ')}`);
  }
  lines.push('');

  lines.push('---');
  lines.push(`*Generated by Verity Case Management System on ${new Date().toISOString()}.*`);

  return lines.join('\n');
}
